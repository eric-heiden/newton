CYCLE_DURATION = 26.154


@wp.kernel
def sample_tool_path(
    times: wp.array[float],
    poses: wp.array[wp.vec4],
    velocities: wp.array[wp.vec4],
    grip_times: wp.array[wp.vec3],
    step_count: wp.array[int],
    dt: float,
    position: wp.array[wp.vec3],
    rotation: wp.array[wp.vec4],
    engaged: wp.array[wp.bool],
    preparing: wp.array[wp.bool],
):
    t = float(step_count[0]) * dt
    lo = int(0)
    while lo < times.shape[0] - 2 and times[lo + 1] <= t:
        lo += 1
    duration = times[lo + 1] - times[lo]
    u = wp.clamp((t - times[lo]) / duration, 0.0, 1.0)
    u2 = u * u
    u3 = u2 * u
    pose = (
        (2.0 * u3 - 3.0 * u2 + 1.0) * poses[lo]
        + (u3 - 2.0 * u2 + u) * duration * velocities[lo]
        + (-2.0 * u3 + 3.0 * u2) * poses[lo + 1]
        + (u3 - u2) * duration * velocities[lo + 1]
    )
    position[0] = wp.vec3(pose[0], pose[1], pose[2])
    q = wp.quat_rpy(0.0, wp.pi * 0.5, pose[3])
    rotation[0] = wp.vec4(q[0], q[1], q[2], q[3])
    engage = bool(False)
    prepare = bool(False)
    for i in range(grip_times.shape[0]):
        event = grip_times[i]
        engage = engage or (t >= event[1] and t < event[2])
        prepare = prepare or (t >= event[0] and t < event[1])
    engaged[0] = engage
    preparing[0] = prepare


@wp.kernel
def write_arm_targets(
    joint_q: wp.array2d[float],
    offset: int,
    targets: wp.array[float],
    step_count: wp.array[int],
):
    dof = wp.tid()
    targets[offset + dof] = joint_q[0, dof]
    if dof == 0:
        step_count[0] += 1


class PalletizerIK:
    """Solve one arm trajectory, shared by the example's identical worlds."""

    def __init__(self, model: newton.Model, flange: int):
        self.model = model
        path = np.asarray(WAYPOINTS, dtype=np.float64)
        values = path[:, 1:].copy()
        values[:, 3] = np.deg2rad(values[:, 3])
        velocities = np.gradient(values, path[:, 0], axis=0)
        velocities[[0, -1]] = 0.0
        self.times = wp.array(path[:, 0], dtype=float, device=model.device)
        self.poses = wp.array(values, dtype=wp.vec4, device=model.device)
        self.velocities = wp.array(velocities, dtype=wp.vec4, device=model.device)
        self.grip_times = wp.array(GRIP_TIMES, dtype=wp.vec3, device=model.device)
        self.position = wp.zeros(1, dtype=wp.vec3, device=model.device)
        self.rotation = wp.zeros(1, dtype=wp.vec4, device=model.device)
        self.position_objective = ik.IKObjectivePosition(
            link_index=flange, link_offset=wp.vec3(0.0), target_positions=self.position
        )
        self.rotation_objective = ik.IKObjectiveRotation(
            link_index=flange, link_offset_rotation=wp.quat_identity(), target_rotations=self.rotation
        )
        self.solver = ik.IKSolver(
            model=model,
            n_problems=1,
            objectives=[
                self.position_objective,
                self.rotation_objective,
                ik.IKObjectiveJointLimit(
                    joint_limit_lower=model.joint_limit_lower,
                    joint_limit_upper=model.joint_limit_upper,
                ),
            ],
            jacobian_mode=ik.IKJacobianType.ANALYTIC,
        )
        # Select the same elbow/wrist branch as the industrial cycle, then solve the home pose.
        home = np.deg2rad([[160.57, -3.50, -10.84, 0.0, -82.66, -116.57]])
        self.joint_q = wp.array(home, dtype=float, device=model.device)
        self.position.assign(values[:1, :3])
        q = wp.quat_rpy(0.0, wp.pi * 0.5, float(values[0, 3]))
        self.rotation.assign(np.asarray([q], dtype=np.float32))
        self.solver.step(self.joint_q, self.joint_q, iterations=32)

    def step(
        self,
        step_count: wp.array[int],
        dt: float,
        offset: int,
        targets: wp.array[float],
        engaged: wp.array[wp.bool],
        preparing: wp.array[wp.bool],
    ):
        """Solve the next flange pose, write joint targets, and advance the sub-step clock."""
        wp.launch(
            sample_tool_path,
            dim=1,
            inputs=[self.times, self.poses, self.velocities, self.grip_times, step_count, dt],
            outputs=[self.position, self.rotation, engaged, preparing],
            device=self.model.device,
        )
        self.position_objective.set_target_positions(self.position)
        self.rotation_objective.set_target_rotations(self.rotation)
        self.solver.step(self.joint_q, self.joint_q, iterations=8)
        wp.launch(
            write_arm_targets,
            dim=self.model.joint_coord_count,
            inputs=[self.joint_q, offset],
            outputs=[targets, step_count],
            device=self.model.device,
        )
